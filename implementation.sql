CREATE TABLE COMPANY (
    company_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_name VARCHAR2(100) NOT NULL,
    industry VARCHAR2(100),
    location VARCHAR2(150),
    email VARCHAR2(100) UNIQUE,
    phone VARCHAR2(15),
    website VARCHAR2(150)
);

CREATE TABLE JOB (
    job_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id NUMBER NOT NULL,
    job_title VARCHAR2(100) NOT NULL,
    job_description CLOB,
    employment_type VARCHAR2(50),
    location VARCHAR2(150),
    min_salary NUMBER(10,2),
    max_salary NUMBER(10,2),
    posted_date DATE DEFAULT SYSDATE NOT NULL,
    closing_date DATE,
    job_status VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    CONSTRAINT fk_job_company FOREIGN KEY (company_id) REFERENCES COMPANY(company_id),
    CONSTRAINT chk_job_min_salary CHECK (min_salary IS NULL OR min_salary >= 0),
    CONSTRAINT chk_job_max_salary CHECK (max_salary IS NULL OR max_salary >= 0),
    CONSTRAINT chk_job_salary_range CHECK (min_salary IS NULL OR max_salary IS NULL OR max_salary >= min_salary),
    CONSTRAINT chk_job_status CHECK (job_status IN ('OPEN','CLOSED','ON_HOLD'))
);

CREATE TABLE JOB_SEEKER (
    seeker_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(100) NOT NULL,
    email VARCHAR2(100) NOT NULL UNIQUE,
    phone VARCHAR2(15),
    qualification VARCHAR2(100),
    experience_years NUMBER(3) DEFAULT 0 CHECK (experience_years >= 0),
    resume_url VARCHAR2(255),
    registered_on DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE SKILL (
    skill_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE SEEKER_SKILL (
    seeker_id NUMBER NOT NULL,
    skill_id NUMBER NOT NULL,
    proficiency_level VARCHAR2(20),
    years_experience NUMBER(3) DEFAULT 0 CHECK (years_experience >= 0),
    CONSTRAINT pk_seeker_skill PRIMARY KEY (seeker_id, skill_id),
    CONSTRAINT fk_ss_seeker FOREIGN KEY (seeker_id) REFERENCES JOB_SEEKER(seeker_id),
    CONSTRAINT fk_ss_skill FOREIGN KEY (skill_id) REFERENCES SKILL(skill_id),
    CONSTRAINT chk_ss_level CHECK (proficiency_level IS NULL OR proficiency_level IN ('BEGINNER','INTERMEDIATE','ADVANCED','EXPERT'))
);

CREATE TABLE JOB_SKILL (
    job_id NUMBER NOT NULL,
    skill_id NUMBER NOT NULL,
    required_level VARCHAR2(20),
    CONSTRAINT pk_job_skill PRIMARY KEY (job_id, skill_id),
    CONSTRAINT fk_js_job FOREIGN KEY (job_id) REFERENCES JOB(job_id),
    CONSTRAINT fk_js_skill FOREIGN KEY (skill_id) REFERENCES SKILL(skill_id),
    CONSTRAINT chk_js_level CHECK (required_level IS NULL OR required_level IN ('BEGINNER','INTERMEDIATE','ADVANCED','EXPERT'))
);

CREATE TABLE APPLICATION (
    application_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seeker_id NUMBER NOT NULL,
    job_id NUMBER NOT NULL,
    applied_on DATE DEFAULT SYSDATE NOT NULL,
    application_status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    cover_letter CLOB,
    resume_url VARCHAR2(255),
    CONSTRAINT fk_application_seeker FOREIGN KEY (seeker_id) REFERENCES JOB_SEEKER(seeker_id),
    CONSTRAINT fk_application_job FOREIGN KEY (job_id) REFERENCES JOB(job_id),
    CONSTRAINT uq_seeker_job UNIQUE (seeker_id, job_id),
    CONSTRAINT chk_application_status CHECK (application_status IN ('PENDING','SHORTLISTED','REJECTED','ACCEPTED','WITHDRAWN'))
);

CREATE TABLE INTERVIEW (
    interview_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id NUMBER NOT NULL,
    scheduled_at DATE NOT NULL,
    interview_mode VARCHAR2(20) NOT NULL,
    interview_location VARCHAR2(150),
    interview_status VARCHAR2(20) DEFAULT 'SCHEDULED' NOT NULL,
    feedback CLOB,
    CONSTRAINT fk_interview_application FOREIGN KEY (application_id) REFERENCES APPLICATION(application_id),
    CONSTRAINT chk_interview_mode CHECK (interview_mode IN ('ONLINE','OFFLINE','PHONE')),
    CONSTRAINT chk_interview_status CHECK (interview_status IN ('SCHEDULED','COMPLETED','CANCELLED'))
);

