SELECT j.job_id,j.job_title,c.company_name,j.location,j.min_salary,j.max_salary
FROM JOB j
JOIN COMPANY c ON j.company_id=c.company_id;

SELECT a.application_id,s.full_name,j.job_title,c.company_name,a.application_status
FROM APPLICATION a
JOIN JOB_SEEKER s ON a.seeker_id=s.seeker_id
JOIN JOB j ON a.job_id=j.job_id
JOIN COMPANY c ON j.company_id=c.company_id;

SELECT s.seeker_id,s.full_name
FROM JOB_SEEKER s
JOIN SEEKER_SKILL ss ON s.seeker_id=ss.seeker_id
JOIN SKILL k ON ss.skill_id=k.skill_id
WHERE k.skill_name IN ('Java','SQL')
GROUP BY s.seeker_id,s.full_name
HAVING COUNT(DISTINCT k.skill_name)=2;

SELECT j.job_id,j.job_title,COUNT(a.application_id) AS total_applications
FROM JOB j
LEFT JOIN APPLICATION a ON j.job_id=a.job_id
GROUP BY j.job_id,j.job_title;

SELECT c.company_id,c.company_name,COUNT(j.job_id) AS total_jobs
FROM COMPANY c
JOIN JOB j ON c.company_id=j.company_id
GROUP BY c.company_id,c.company_name
HAVING COUNT(j.job_id)>1;

